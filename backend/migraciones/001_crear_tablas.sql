-- Esquema base multi-tenant (Prompt 1). Ejecutar sobre una BD vacía en UTF-8.
-- BY DEFAULT permite ids explícitos en las semillas; al final se ajustan las secuencias.

CREATE EXTENSION IF NOT EXISTS pgcrypto; -- gen_salt/crypt para las contraseñas de ejemplo

-- ---------------------------------------------------------------
-- usuarios: maestros y alumnos
-- ---------------------------------------------------------------
CREATE TABLE usuarios (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre            TEXT NOT NULL,
  email             TEXT NOT NULL UNIQUE,
  contrasena_hash   TEXT NOT NULL,
  rol               TEXT NOT NULL CHECK (rol IN ('maestro', 'alumno')),
  xp                INTEGER NOT NULL DEFAULT 0 CHECK (xp >= 0),
  racha             INTEGER NOT NULL DEFAULT 0 CHECK (racha >= 0),
  ultima_actividad  TIMESTAMPTZ,
  creado_en         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------
-- cursos: cada curso pertenece a un maestro
-- ---------------------------------------------------------------
CREATE TABLE cursos (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  maestro_id         BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  nombre             TEXT NOT NULL,
  idioma             TEXT NOT NULL DEFAULT 'ruso',
  descripcion        TEXT,
  codigo_invitacion  TEXT NOT NULL UNIQUE
                       CHECK (char_length(codigo_invitacion) BETWEEN 6 AND 8),
  creado_en          TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_cursos_maestro ON cursos (maestro_id);

-- ---------------------------------------------------------------
-- inscripciones: alumnos en cursos (llave primaria compuesta)
-- ---------------------------------------------------------------
CREATE TABLE inscripciones (
  usuario_id  BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  curso_id    BIGINT NOT NULL REFERENCES cursos (id) ON DELETE CASCADE,
  fecha       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (usuario_id, curso_id)
);

CREATE INDEX idx_inscripciones_curso ON inscripciones (curso_id);

-- ---------------------------------------------------------------
-- lecciones: unidades de un curso, pueden estar en borrador
-- ---------------------------------------------------------------
CREATE TABLE lecciones (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  curso_id     BIGINT NOT NULL REFERENCES cursos (id) ON DELETE CASCADE,
  titulo       TEXT NOT NULL,
  descripcion  TEXT,
  orden        INTEGER NOT NULL DEFAULT 0,
  publicada    BOOLEAN NOT NULL DEFAULT false
);

CREATE INDEX idx_lecciones_curso ON lecciones (curso_id);

-- ---------------------------------------------------------------
-- tarjetas: "palabra" es el campo principal, válido para cualquier idioma
-- ---------------------------------------------------------------
CREATE TABLE tarjetas (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  leccion_id      BIGINT NOT NULL REFERENCES lecciones (id) ON DELETE CASCADE,
  palabra         TEXT NOT NULL,
  transliteracion TEXT NOT NULL,
  traduccion      TEXT NOT NULL,
  imagen_url      TEXT,
  CONSTRAINT tarjetas_leccion_palabra_unico UNIQUE (leccion_id, palabra)
);

CREATE INDEX idx_tarjetas_leccion ON tarjetas (leccion_id);

-- ---------------------------------------------------------------
-- progreso_tarjetas: caja Leitner por alumno y tarjeta
-- ---------------------------------------------------------------
CREATE TABLE progreso_tarjetas (
  usuario_id       BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  tarjeta_id       BIGINT NOT NULL REFERENCES tarjetas (id) ON DELETE CASCADE,
  caja             SMALLINT NOT NULL DEFAULT 1 CHECK (caja BETWEEN 1 AND 5),
  proxima_revision DATE NOT NULL DEFAULT CURRENT_DATE,
  PRIMARY KEY (usuario_id, tarjeta_id)
);

CREATE INDEX idx_progreso_usuario_proxima
  ON progreso_tarjetas (usuario_id, proxima_revision);
CREATE INDEX idx_progreso_proxima_revision
  ON progreso_tarjetas (proxima_revision);

-- ---------------------------------------------------------------
-- resultados_quiz: historial de puntajes
-- ---------------------------------------------------------------
CREATE TABLE resultados_quiz (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id       BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  leccion_id       BIGINT NOT NULL REFERENCES lecciones (id) ON DELETE CASCADE,
  puntaje          INTEGER NOT NULL CHECK (puntaje >= 0),
  total_preguntas  INTEGER NOT NULL CHECK (total_preguntas > 0),
  fecha            TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_resultados_usuario_fecha
  ON resultados_quiz (usuario_id, fecha DESC);
CREATE INDEX idx_resultados_leccion ON resultados_quiz (leccion_id);

-- ---------------------------------------------------------------
-- suscripciones: una por maestro
-- ---------------------------------------------------------------
CREATE TABLE suscripciones (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  maestro_id    BIGINT NOT NULL UNIQUE REFERENCES usuarios (id) ON DELETE CASCADE,
  plan          TEXT NOT NULL DEFAULT 'gratis' CHECK (plan IN ('gratis', 'pro')),
  estado        TEXT NOT NULL DEFAULT 'activa',
  renovacion    DATE,
  proveedor_id  TEXT
);

CREATE INDEX idx_suscripciones_maestro ON suscripciones (maestro_id);
