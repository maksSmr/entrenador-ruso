-- Prompt 1b: verificación de correo y restablecimiento de contraseña.
-- ALTER TABLE no pierde datos de la migración 001. Se puede ejecutar más de una vez.

ALTER TABLE usuarios
  ADD COLUMN IF NOT EXISTS email_verificado BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS verificado_en TIMESTAMPTZ;

-- No se marca nadie automáticamente: el registro siempre exige verificación.
-- Las semillas marcan explícitamente a los usuarios de ejemplo como verificados.

CREATE TABLE IF NOT EXISTS tokens_verificacion (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  token_hash  TEXT NOT NULL UNIQUE,
  tipo        TEXT NOT NULL CHECK (tipo IN ('verificar_email', 'restablecer_contrasena')),
  expira_en   TIMESTAMPTZ NOT NULL,
  usado_en    TIMESTAMPTZ,
  creado_en   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tokens_usuario ON tokens_verificacion (usuario_id);
CREATE INDEX IF NOT EXISTS idx_tokens_hash ON tokens_verificacion (token_hash);

SELECT setval(
  pg_get_serial_sequence('tokens_verificacion', 'id'),
  (SELECT COALESCE(MAX(id), 1) FROM tokens_verificacion)
);
