-- Prompt 12c: historial real de aciertos/fallos para el reporte del maestro.
CREATE TABLE IF NOT EXISTS respuestas_repaso (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  tarjeta_id  BIGINT NOT NULL REFERENCES tarjetas (id) ON DELETE CASCADE,
  acerto      BOOLEAN NOT NULL,
  fecha       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_respuestas_tarjeta_acerto
  ON respuestas_repaso (tarjeta_id, acerto);
CREATE INDEX IF NOT EXISTS idx_respuestas_usuario_fecha
  ON respuestas_repaso (usuario_id, fecha DESC);
