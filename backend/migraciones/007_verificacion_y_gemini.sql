-- Verificación de correo reforzada + campo para notas de tarjetas generadas con IA.
-- Idempotente: se puede ejecutar más de una vez en Neon sin perder datos.

-- La verificación sigue teniendo su fuente de verdad en tokens_verificacion
-- (token_hash + expira_en). Estas columnas de usuarios dejan el estado visible
-- y son compatibles con consultas sencillas desde reportes o soporte.
ALTER TABLE usuarios
  ADD COLUMN IF NOT EXISTS email_verificado BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS verificado_en TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS token_verificacion_hash TEXT,
  ADD COLUMN IF NOT EXISTS expiracion_token_verificacion TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS idx_usuarios_email ON usuarios (email);

-- Por si la migración 002 no se hubiera aplicado todavía: misma definición.
CREATE TABLE IF NOT EXISTS tokens_verificacion (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  token_hash  TEXT NOT NULL UNIQUE,
  tipo        TEXT NOT NULL CHECK (tipo IN ('verificar_email', 'restablecer_contrasena')),
  expira_en   TIMESTAMPTZ NOT NULL,
  usado_en    TIMESTAMPTZ,
  creado_en   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tokens_usuario ON tokens_verificacion (usuario_id);
CREATE INDEX IF NOT EXISTS idx_tokens_hash ON tokens_verificacion (token_hash);

-- Nota gramatical/contextual propuesta por Gemini. Opcional y retrocompatible.
ALTER TABLE tarjetas
  ADD COLUMN IF NOT EXISTS nota_gramatical TEXT;

SELECT setval(
  pg_get_serial_sequence('tokens_verificacion', 'id'),
  (SELECT COALESCE(MAX(id), 1) FROM tokens_verificacion)
);
